// Copies Zen's selectable folder icons into the extension, for the popup's icon picker.
// Extension pages can't load chrome:// images, so the extension ships its own copies.
//
//   node scripts/import-icons.mjs <zen-desktop>/src/browser/themes/shared/zen-icons/common/selectable
//
// Writes extension/icons/zen/<name>.svg (one per entry in ICONS), extension/icons/zen/LICENSE.md and
// extension/shared/icons.css (one mask class per icon). The icons are Ionicons (MIT), shipped by Zen
// with an MPL-2.0 header that each copy keeps as an XML comment.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { ICONS } from "../extension/shared/icons.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = join(ROOT, "extension", "icons", "zen");
const CSS_FILE = join(ROOT, "extension", "shared", "icons.css");

// Anything that could load or run something. Images loaded through CSS never run scripts, but a copy
// that needs any of these is not a plain icon and should be looked at by hand.
const FORBIDDEN = [/<script/i, /\son\w+\s*=/i, /href\s*=\s*["'](?!#)/i, /<foreignObject/i, /url\(/i, /<!ENTITY/i];

const HEADER =
  "<!-- This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0. If a copy of the MPL\n" +
  "     was not distributed with this file, You can obtain one at http://mozilla.org/MPL/2.0/.\n" +
  "     Icon from Ionicons (https://ionic.io/ionicons) by Ionic, MIT License; copied from Zen Browser. -->\n";

function convert(name, source) {
  const body = source
    .split(/\r?\n/)
    .filter((line) => !line.startsWith("#"))
    .join("\n")
    .trim();
  if (!body.startsWith("<svg")) throw new Error(`${name}.svg: expected <svg> after the header`);
  for (const pattern of FORBIDDEN) {
    if (pattern.test(body)) throw new Error(`${name}.svg: unexpected content (${pattern})`);
  }
  // Used as a CSS mask, so only the alpha channel matters; the colour comes from the element.
  const solid = body.replaceAll('"context-fill-opacity"', '"1"').replaceAll('"context-fill"', '"#000"');
  if (solid.includes("context-")) throw new Error(`${name}.svg: unhandled context property`);
  return HEADER + solid + "\n";
}

const sourceDir = process.argv[2];
if (!sourceDir || !existsSync(sourceDir)) {
  console.error("usage: node scripts/import-icons.mjs <path to zen-icons/common/selectable>");
  process.exit(1);
}

mkdirSync(OUT_DIR, { recursive: true });
for (const name of ICONS) {
  const file = join(sourceDir, `${name}.svg`);
  if (!existsSync(file)) throw new Error(`missing ${name}.svg in ${sourceDir}`);
  writeFileSync(join(OUT_DIR, `${name}.svg`), convert(name, readFileSync(file, "utf8")));
}

