// Every code point as a 6-digit escape (\002063). Six digits need no terminating space, so escapes can sit side by
// side and right before the closing quote, and the file stays plain ASCII.
export function cssEscape(text) {
  let out = "";
  for (const ch of text) out += "\\" + ch.codePointAt(0).toString(16).toUpperCase().padStart(6, "0");
  return out;
}

// A tidy group, optionally with one icon code: a plain tab-group whose label starts with SIG (+ code). Split views
// (label "" or U+200B), the user's own groups and Zen folders (<zen-folder>) can never match.
export function groupSelector(code = "") {
  return `tab-group[label^="${cssEscape(SIG + code)}"]`;
}

