function comment(lines) {
  if (lines.length === 1) return `/* ${lines[0]} */`;
  return ["/* " + lines[0], ...lines.slice(1).map((line) => (line ? " * " + line : " *"))].join("\n") + " */";
}

// declarations: [property, value, note]. The note says where the value comes from.
function rule(selector, declarations) {
  const body = declarations.map(([property, value, note]) => `  ${property}: ${value};${note ? ` /* ${note} */` : ""}`);
  return `${selector} {\n${body.join("\n")}\n}`;
}

