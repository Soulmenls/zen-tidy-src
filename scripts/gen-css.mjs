export function buildCss() {
  return [HEADER, GENERIC, CODES, COLLAPSE, FOLDER_LOOK].join("\n\n") + "\n";
}

export function parseArgs(argv) {
  const opts = { out: null, check: false, help: false };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--help" || arg === "-h") opts.help = true;
    else if (arg === "--check") opts.check = true;
    else if (arg === "--out") {
      const value = argv[++i];
      if (!value || value.startsWith("--")) throw new Error("--out needs a value");
      opts.out = value;
    } else throw new Error(`Unknown argument: ${arg}`);
  }
  return opts;
}

// A Windows checkout with core.autocrlf turns the committed LF file into CRLF; that is not drift.
const sameCss = (a, b) => a.replaceAll("\r\n", "\n") === b;

export function main(argv = process.argv.slice(2)) {
  const opts = parseArgs(argv);
  if (opts.help) {
    console.log(USAGE);
    return 0;
  }
  const out = path.resolve(opts.out ?? DEFAULT_OUT);
  const css = buildCss();
  if (opts.check) {
    let current = null;
    try {
      current = readFileSync(out, "utf8");
    } catch {
      current = null;
    }
    if (current === null || !sameCss(current, css)) {
      console.error(`gen-css: ${out} is missing or out of date; run npm run gen:css`);
      return 1;
    }
    console.log(`${out} is up to date`);
    return 0;
  }
  mkdirSync(path.dirname(out), { recursive: true });
  writeFileSync(out, css);
  console.log(`${out} (${ICONS.length} icons)`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main();
  } catch (err) {
    console.error(`gen-css: ${err.message}`);
    console.error(USAGE);
    process.exitCode = 1;
  }
}
